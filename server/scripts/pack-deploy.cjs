function fail(message) {
  console.error(`[deploy:zip] ERROR: ${message}`);
  process.exit(1);
}

function parseEnv(text) {
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq <= 0) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

function buildDeployEnv() {
  const envPath = path.join(SERVER_DIR, ".env");
  if (!fs.existsSync(envPath)) {
    fail("server/.env not found — needed to generate the deploy.env fallback credentials.");
  }
  const local = parseEnv(fs.readFileSync(envPath, "utf8"));

  if (local.MYSQL_DB_USER && local.MYSQL_DB_PASSWORD) {
    const encPass = encodeURIComponent(local.MYSQL_DB_PASSWORD);
    PRODUCTION_OVERRIDES.DATABASE_URL = `mysql://${local.MYSQL_DB_USER}:${encPass}@kms.596.mytemp.website:3306/reservation?sslmode=disable&connect_timeout=30&pool_timeout=30`;
  }

  const merged = { ...local, ...PRODUCTION_OVERRIDES };

  const missing = REQUIRED_FALLBACK_KEYS.filter((key) => !merged[key]);
  if (missing.length > 0) {
    fail(`deploy.env fallback missing real values in server/.env: ${missing.join(", ")}`);
  }
  if (merged.JWT_SECRET === "dev-only-insecure-secret-change-me") {
    fail("JWT_SECRET in server/.env is the insecure dev fallback. Set a real secret.");
  }

  const lines = ENV_KEYS.filter((key) => merged[key] !== undefined).map(
    (key) => `${key}=${merged[key]}`,
  );
  return [
    "# Generated by scripts/pack-deploy.cjs at pack time.",
    "# Fallback only: platform/dashboard environment variables take priority.",
    ...lines,
    "",
  ].join("\n");
}

async function main() {
  // archiver v8 is ESM-only with no factory function, so dynamic
  // import + `new ZipArchive()` from this .cjs script.
  const { ZipArchive } = await import("archiver");

  for (const entry of [...FILES, ...DIRS]) {
    if (!fs.existsSync(path.join(SERVER_DIR, entry))) {
      fail(`missing required entry: ${entry} (run from the server folder)`);
    }
  }
  if (!fs.existsSync(path.join(SERVER_DIR, "dist", "server.js"))) {
    fail("dist/server.js not found. Run `npm run compile` first.");
  }
  // Guarantee latest code: dist must be newer than every src file.
  // deploy:zip always builds first, this also protects direct runs.
  const distMtime = fs.statSync(path.join(SERVER_DIR, "dist", "server.js")).mtimeMs;
  const stack = [path.join(SERVER_DIR, "src")];
  while (stack.length > 0) {
    const current = stack.pop();
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      const full = path.join(current, entry.name);
      if (entry.isDirectory()) stack.push(full);
      else if (entry.isFile() && fs.statSync(full).mtimeMs > distMtime) {
        fail(`stale dist: ${entry.name} changed after last build. Run fresh, don't pack by hand.`);
      }
    }
  }

  const deployEnv = buildDeployEnv();

  if (fs.existsSync(OUT_ZIP)) fs.rmSync(OUT_ZIP);

  const output = fs.createWriteStream(OUT_ZIP);
  const archive = new ZipArchive({ zlib: { level: 9 } });

  output.on("close", () => {
    const mb = archive.pointer() / 1024 / 1024;
    console.log(`[deploy:zip] packed: ${OUT_ZIP} (${mb.toFixed(2)} MB)`);
    if (mb > 90) {
      console.warn("[deploy:zip] WARNING: over 90 MB, GoDaddy zip limit is 100 MB.");
    }
    console.log("[deploy:zip] deploy.env fallback included (dashboard env still wins).");
    console.log(
      "[deploy:zip] Upload it via: host.godaddy.com > Node.js Hosting > server > Update Preview",
    );
  });

  archive.on("warning", (err) => {
    if (err.code === "ENOENT") console.warn(`[deploy:zip] skipped: ${err.message}`);
    else fail(err.message);
  });
  archive.on("error", (err) => fail(err.message));

  archive.pipe(output);
  for (const file of FILES) archive.file(path.join(SERVER_DIR, file), { name: file });
  for (const dir of DIRS) archive.directory(path.join(SERVER_DIR, dir), dir);
  archive.append(deployEnv, { name: "deploy.env" });
  await archive.finalize();
}

main().catch((err) => fail(err instanceof Error ? err.message : String(err)));
