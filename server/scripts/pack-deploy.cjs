// One-command deploy pack for GoDaddy Node.js Hosting.
// Usage: npm run deploy:zip   (compiles first, then packs)
// Output: server-godaddy-deploy.zip (this folder)
// Layout inside zip: package.json + package-lock.json at root, plus src, scripts, dist.
// Never included: node_modules, raw .env, logs, tests, old zips.
// deploy.env is generated from server/.env at pack time (gitignored) and acts
// as a low-priority fallback: dashboard env > .env > deploy.env.
// Plain Node + archiver (devDependency), works on any OS.
const fs = require("node:fs");
const path = require("node:path");

const SERVER_DIR = path.join(__dirname, "..");
const OUT_ZIP = path.join(SERVER_DIR, "server-godaddy-deploy.zip");

// Top-level entries only: keeps node_modules, .env and logs out by design.
